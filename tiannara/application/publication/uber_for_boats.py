"""Uber-for-Boats publication acceptance placeholder.

This scenario is deliberately blocked until real compilation, independent
certification, exact artifact bytes, and a live publication provider exist.
It must never manufacture a CERTIFIED ledger event to make the demo pass.
"""
from tiannara.application.evolution.ledger import EvolutionLedger
from tiannara.application.publication.deployment_handoff import handoff_to_deployment


def run_uber_for_boats(
    github_token: str = "",
    ledger: EvolutionLedger | None = None,
):
    # Keep the token parameter for caller compatibility, but do not inspect,
    # persist, log, or pass credentials to an unimplemented provider.
    del github_token
    evidence_ledger = ledger if ledger is not None else EvolutionLedger()
    del evidence_ledger

    blockers = [
        "No authoritative requirements/ISR or compiled candidate is generated by this demonstration.",
        "No independently earned certification reference is supplied; the demo will not create one.",
        "The GitHub provider has no live API implementation.",
        "No live deployment adapter is configured.",
    ]
    deployment = handoff_to_deployment("")
    return {
        "idea": "I want an Uber for boats.",
        "status": "BLOCKED",
        "bundle": None,
        "files": [],
        "repo_url": None,
        "ledger_ref": None,
        "deployment": deployment,
        "verified": False,
        "published": False,
        "verification_blockers": blockers + list(deployment["blockers"]),
    }
